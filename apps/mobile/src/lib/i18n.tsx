export type StringKey = keyof (typeof STRINGS)["sv"];

export function deviceLocale(): Locale {
  return getLocales()[0]?.languageCode === "sv" ? "sv" : "en";
}

export function deviceCurrency(): string {
  return getLocales()[0]?.currencyCode ?? "EUR";
}

const LocaleContext = createContext<Locale>("en");

export function LocaleProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>;
}

export function useLocale(): Locale {
  return useContext(LocaleContext);
}

export function useT() {
  const locale = useLocale();
  return (key: StringKey, vars: Record<string, string | number> = {}) =>
    STRINGS[locale][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}
